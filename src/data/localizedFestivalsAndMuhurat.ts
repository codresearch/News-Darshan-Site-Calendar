export function getLocalizedTithiName(rawTithi: string, lang: LanguageCode): string {
  if (!rawTithi) return '';
  if (lang === 'en') return rawTithi;

  // Check direct festival/tithi names in string like "Makar Sankranti", "Gudi Padwa", "Dhanteras"
  for (const [key, fest] of Object.entries(FESTIVAL_TRANSLATIONS)) {
    if (rawTithi.toLowerCase().includes(fest.name.en.toLowerCase())) {
      return fest.name[lang] || rawTithi;
    }
  }

  // Translate paksha + tithi e.g. "Shukla Dashami" -> "शुक्ल दशमी"
  let result = rawTithi;
  const isShukla = rawTithi.includes('Shukla');
  const isKrishna = rawTithi.includes('Krishna');

  for (const [tithiKey, trans] of Object.entries(TITHI_TRANSLATIONS)) {
    if (rawTithi.includes(tithiKey)) {
      const translatedTithi = trans[lang] || tithiKey;
      if (isShukla) {
        const pakshaWord = lang === 'hi' || lang === 'mr' ? 'शुक्ल' : lang === 'gu' ? 'શુક્લ' : lang === 'te' ? 'శుక్ల' : lang === 'ta' ? 'சுக்ல' : lang === 'kn' ? 'ಶುಕ್ಲ' : lang === 'ml' ? 'ശുക്ല' : lang === 'bn' ? 'শুক্ল' : lang === 'or' ? 'ଶୁକ୍ଳ' : lang === 'pa' ? 'ਸ਼ੁਕਲ' : lang === 'as' ? 'শুক্ল' : 'Shukla';
        return `${pakshaWord} ${translatedTithi}`;
      }
      if (isKrishna) {
        const pakshaWord = lang === 'hi' || lang === 'mr' ? 'कृष्ण' : lang === 'gu' ? 'કૃષ્ણ' : lang === 'te' ? 'కృష్ణ' : lang === 'ta' ? 'கிருஷ்ண' : lang === 'kn' ? 'ಕೃಷ್ಣ' : lang === 'ml' ? 'കൃഷ്ണ' : lang === 'bn' ? 'কৃষ্ণ' : lang === 'or' ? 'କୃଷ୍ଣ' : lang === 'pa' ? 'ਕ੍ਰਿਸ਼ਨ' : lang === 'as' ? 'কৃষ্ণ' : 'Krishna';
        return `${pakshaWord} ${translatedTithi}`;
      }
      return translatedTithi;
    }
  }

  return result;
}

export function getLocalizedNakshatraName(rawNakshatra: string, lang: LanguageCode): string {
  if (!rawNakshatra) return '';
  if (lang === 'en') return rawNakshatra;

  const match = NAKSHATRA_TRANSLATIONS[rawNakshatra];
  if (match && match[lang]) return match[lang]!;

  for (const [key, trans] of Object.entries(NAKSHATRA_TRANSLATIONS)) {
    if (rawNakshatra.includes(key)) {
      return trans[lang] || key;
    }
  }
  return rawNakshatra;
}

export function getLocalizedTimeWindow(timeWindow: string, lang: LanguageCode): string {
  if (!timeWindow || lang === 'en') return timeWindow;

  let localized = timeWindow;
  if (lang === 'hi' || lang === 'mr') {
    localized = localized
      .replace(/AM/g, 'सुबह / प्रातः')
      .replace(/PM/g, 'दोपहर / सायं')
      .replace(/to/g, 'से')
      .replace(/\(Overnight\)/g, '(रात्रि पर्यंत)')
      .replace(/All Day/g, 'संपूर्ण दिवस (अभिजीत)');
  } else if (lang === 'gu') {
    localized = localized
      .replace(/AM/g, 'સવારે')
      .replace(/PM/g, 'બપોરે / સાંજે')
      .replace(/to/g, 'થી')
      .replace(/\(Overnight\)/g, '(રાત્રિ પર્યંત)');
  } else if (lang === 'te') {
    localized = localized
      .replace(/AM/g, 'ఉదయం')
      .replace(/PM/g, 'సాయంత్రం')
      .replace(/to/g, 'నుండి');
  } else if (lang === 'ta') {
    localized = localized
      .replace(/AM/g, 'காலை')
      .replace(/PM/g, 'மாலை')
      .replace(/to/g, 'முதல்');
  } else if (lang === 'bn') {
    localized = localized
      .replace(/AM/g, 'সকাল')
      .replace(/PM/g, 'বিকাল/সন্ধ্যা')
      .replace(/to/g, 'থেকে');
  }
  return localized;
}
