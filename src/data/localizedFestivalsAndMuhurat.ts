export function getFestivalName(festOrId: FestivalEvent | string, lang: LanguageCode): string {
  const id = typeof festOrId === 'string' ? festOrId : festOrId.id || festOrId.slug;
  const match = FESTIVAL_TRANSLATIONS[id];
  if (match && match.name[lang]) {
    return match.name[lang];
  }
  if (typeof festOrId !== 'string') {
    if (festOrId.nameRegional && festOrId.nameRegional[lang]) {
      return festOrId.nameRegional[lang];
    }
    if ((lang === 'hi' || lang === 'mr') && festOrId.nameHi) {
      return festOrId.nameHi;
    }
    return festOrId.name;
  }
  return id;
}

