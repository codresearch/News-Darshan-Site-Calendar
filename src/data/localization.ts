/**
 * Universal safe translation getter with English fallback
 */
export function getUIText(lang: LanguageCode, key: string, fallback?: string): string {
  const dict = UI_TRANSLATIONS[lang] || UI_TRANSLATIONS.en;
  if (dict && dict[key]) {
    return dict[key];
  }
  const enDict = UI_TRANSLATIONS.en;
  if (enDict && enDict[key]) {
    return enDict[key];
  }
  return fallback || key;
}

