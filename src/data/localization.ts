export function getWeekdayLocalized(dayString: string, lang: LanguageCode): string {
  for (const [key, map] of Object.entries(LOCALIZED_WEEKDAYS)) {
    if (dayString.toLowerCase().includes(key.toLowerCase())) {
      return map[lang] || map.hi || dayString;
    }
  }
  return dayString;
}

export function getPakshaLocalized(paksha: string, lang: LanguageCode): string {
  const match = LOCALIZED_PAKSHA[paksha];
  if (match && match[lang]) return match[lang]!;
  if (lang === 'hi' || lang === 'mr') return `${paksha} पक्ष`;
  return `${paksha} Paksha`;
}

